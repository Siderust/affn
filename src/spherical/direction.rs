    #[test]
    fn folds_polar_to_valid_range() {
        use crate::spherical::canonicalize_polar;
        assert!((canonicalize_polar(Degrees::new(100.0)).value() - 80.0).abs() < EPS);
        assert!((canonicalize_polar(Degrees::new(-100.0)).value() - (-80.0)).abs() < EPS);
    }

    #[test]
    fn canonicalizes_angle_pair_across_poles() {
        use crate::spherical::canonicalize_polar_azimuth;

        let (polar, azimuth) = canonicalize_polar_azimuth(100.0 * DEG, 30.0 * DEG);
        assert!((polar.value() - 80.0).abs() < EPS);
        assert!((azimuth.value() - 210.0).abs() < EPS);

        let (polar, azimuth) = canonicalize_polar_azimuth(-100.0 * DEG, 30.0 * DEG);
        assert!((polar.value() + 80.0).abs() < EPS);
        assert!((azimuth.value() - 210.0).abs() < EPS);
    }

