/// A spherical direction (unit vector) in a specific reference frame.
///
/// Directions are frame-dependent but center-independent (free vectors).
/// They cannot undergo center transformations, only frame transformations.
///
/// The direction stores only angles; the implicit radius is always 1.
/// For a spherical coordinate with explicit distance, use [`Position`](super::Position).
///
/// # Type Parameters
/// - `F`: The reference frame (defines axis orientation)
///
/// # Invariants
///
/// - `polar` is in `[-90°, +90°]`
/// - `azimuth` is in `[0°, 360°)`
#[derive(Debug, Clone, Copy)]
pub struct Direction<F: ReferenceFrame> {
    /// Polar angle (θ) - latitude, declination, or altitude, in degrees.
    /// Range: `[-90°, +90°]`
    pub polar: Degrees,
    /// Azimuthal angle (φ) - longitude, right ascension, or azimuth, in degrees.
    /// Range: `[0°, 360°)`
    pub azimuth: Degrees,
    _frame: PhantomData<F>,
}

impl<F: ReferenceFrame> Direction<F> {
    /// Creates a direction from raw angle values without canonicalization.
    ///
    /// The caller must ensure angles are within canonical ranges:
    /// - `polar` in `[-90°, +90°]`
    /// - `azimuth` in `[0°, 360°)`
    ///
    /// For frame-specific constructors that canonicalize automatically, see the
    /// `new` method generated by `#[derive(ReferenceFrame)]` for spherical frames
    /// (e.g., `Direction::<ICRS>::new(ra, dec)`).
    pub const fn new_unchecked(polar: Degrees, azimuth: Degrees) -> Self {
        Self {
            polar,
            azimuth,
            _frame: PhantomData,
        }
    }

    /// Promotes this direction to a full Position with the supplied radial magnitude.
    ///
    /// # Type Parameters
    /// - `C`: The center for the resulting position
    /// - `U`: The length unit for the magnitude
    ///
    /// # Example
    /// ```rust
    /// use affn::spherical::Direction;
    /// use affn::frames::ReferenceFrame;
    /// use affn::centers::ReferenceCenter;
    /// use qtty::units::*; use qtty::{Quantity, M, KM, DEG, RAD, SEC}; use qtty::angular::{Degrees, Radians}; use qtty::length::{Meters, Kilometers};
    ///
    /// #[derive(Debug, Copy, Clone)]
    /// struct WorldFrame;
    /// impl ReferenceFrame for WorldFrame {
    ///     fn frame_name() -> &'static str { "WorldFrame" }
    /// }
    ///
    /// #[derive(Debug, Copy, Clone)]
    /// struct WorldOrigin;
    /// impl ReferenceCenter for WorldOrigin {
    ///     type Params = ();
    ///     fn center_name() -> &'static str { "WorldOrigin" }
    /// }
    ///
    /// let dir = Direction::<WorldFrame>::new_unchecked(0.0*DEG, 0.0*DEG);
    /// let pos = dir.position::<WorldOrigin, Meter>(1.0*M);
    /// assert_eq!(pos.distance.value(), 1.0);
    /// ```
    #[must_use]
    pub fn position<C, U>(&self, magnitude: Quantity<U>) -> super::Position<C, F, U>
    where
        C: ReferenceCenter<Params = ()>,
        U: LengthUnit,
    {
        super::Position::new_unchecked(self.polar, self.azimuth, magnitude)
    }

    /// Promotes this direction to a Position with explicit center parameters.
    #[must_use]
    pub fn position_with_params<C, U>(
        &self,
        center_params: C::Params,
        magnitude: Quantity<U>,
    ) -> super::Position<C, F, U>
    where
        C: ReferenceCenter,
        U: LengthUnit,
    {
        super::Position::new_unchecked_with_params(
            center_params,
            self.polar,
            self.azimuth,
            magnitude,
        )
    }

    /// Calculates the angular separation between this direction and another
    /// using the Vincenty formula (numerically stable).
    pub fn angular_separation(&self, other: &Self) -> Degrees {
        super::angular_separation_impl(self.polar, self.azimuth, other.polar, other.azimuth)
    }

    /// Returns the oriented great-circle bearing from `self` towards `other`.
    ///
    /// The angle is measured in the tangent plane at `self`, from locally
    /// increasing `polar` (latitude, towards the north pole) towards locally
    /// increasing `azimuth` (longitude, east). Defined results are typed radians
    /// in `[0, 2π)`. In an equatorial frame this is position angle north through
    /// east. Unlike [`Self::angular_separation`], this is an orientation, not an
    /// angular distance, and depends on the frame's polar/azimuth conventions.
    ///
    /// Both directions must use the same frame `F`. A frame does not encode an
    /// observation origin; callers must ensure a common origin whenever their
    /// physical interpretation requires one.
    ///
    /// # Undefined and numerical cases
    ///
    /// Returns `None` for coincident or antipodal directions, a starting point
    /// at either pole (no unique local north), or any non-finite input. As with
    /// [`Self::new_unchecked`], finite angles must satisfy the canonical ranges.
    /// A destination at a pole is valid when the starting point is not a pole.
    ///
    /// For latitudes `a`, `b` and longitude difference `d`, the east and north
    /// tangent components are `cos(b) sin(d)` and
    /// `sin(b-a) cos²(d/2) + sin(b+a) sin²(d/2)`. Their `atan2(east, north)`
    /// gives the bearing. This identity avoids subtracting nearly equal
    /// products near coincidence and antipodality. Differences and complements
    /// are formed in the stored degrees before trigonometric evaluation, also
    /// preserving precision near poles and longitude boundaries.
    ///
    /// No angular tolerance is used: exact coordinate relations detect the
    /// geometric singularities. If both computed tangent components vanish
    /// (including underflow), returns `None` rather than an arbitrary bearing.
    /// Extremely small offsets may be lost to floating-point rounding or
    /// underflow; bearings near singularities are inherently sensitive to input
    /// error. Normalization maps a rounded `2π` to zero.
    ///
    /// # Example
    ///
    /// ```rust
    /// use affn::{prelude::*, spherical::Direction};
    /// use affn::qtty::{angular::Radians, units::Radian, DEG};
    ///
    /// #[derive(Debug, Copy, Clone, ReferenceFrame)]
    /// struct World;
    ///
    /// let a = Direction::<World>::new_unchecked(0.0 * DEG, 350.0 * DEG);
    /// let b = Direction::<World>::new_unchecked(0.0 * DEG, 10.0 * DEG);
    /// let angle = a.position_angle_to(&b);
    /// let east = (90.0 * DEG).to::<Radian>();
    /// assert!((angle.unwrap() - east).abs() < Radians::new(1e-14));
    /// ```
    #[must_use]
    pub fn position_angle_to(&self, other: &Self) -> Option<Radians> {
        let a = self.polar.value();
        let b = other.polar.value();
        let lon_a = self.azimuth.value();
        let lon_b = other.azimuth.value();
        if !a.is_finite()
            || !b.is_finite()
            || !lon_a.is_finite()
            || !lon_b.is_finite()
            || a.abs() == 90.0
        {
            return None;
        }

        let sin = |degrees: f64| Degrees::new(degrees).sin();
        let cos = |degrees: f64| Degrees::new(degrees).cos();
        let square = |x: f64| x * x;
        let raw_delta = lon_b - lon_a;
        // Reduce near 0/360 and 180 *before* conversion to radians. In the
        // antipodal branch, subtract 180 from the larger longitude first so
        // a rounded raw_delta cannot hide a small, representable residual.
        let (east_factor, cos_half_sq, sin_half_sq, coincident_lon, antipodal_lon) =
            if raw_delta.abs() > 90.0 && raw_delta.abs() <= 270.0 {
                let residual = if raw_delta > 0.0 {
                    (lon_b - 180.0) - lon_a
                } else {
                    (lon_a - 180.0) - lon_b
                };
                (
                    -raw_delta.signum() * sin(residual),
                    square(sin(residual * 0.5)),
                    square(cos(residual * 0.5)),
                    false,
                    residual == 0.0,
                )
            } else {
                let delta = if raw_delta > 270.0 {
                    -((360.0 - lon_b) + lon_a)
                } else if raw_delta < -270.0 {
                    (360.0 - lon_a) + lon_b
                } else {
                    raw_delta
                };
                (
                    sin(delta),
                    square(cos(delta * 0.5)),
                    square(sin(delta * 0.5)),
                    delta == 0.0,
                    false,
                )
            };
        if (a == b && coincident_lon) || (a == -b && antipodal_lon) {
            return None;
        }

        // sin(x+y), using pole complements when a sum approaches ±180°.
        // The small complements survive even if x+y itself rounds to ±180°.
        let sin_sum = |x: f64, y: f64| {
            if x * y > 0.0 && (x + y).abs() > 90.0 {
                x.signum() * sin((90.0 - x.abs()) + (90.0 - y.abs()))
            } else {
                sin(x + y)
            }
        };
        let east = sin(90.0 - b.abs()) * east_factor;
        let north = sin_sum(b, -a) * cos_half_sq + sin_sum(b, a) * sin_half_sq;
        if east == 0.0 && north == 0.0 {
            return None;
        }
        let angle = qtty::Transcendental::atan2(east, north);
        let angle = if angle < 0.0 {
            angle + core::f64::consts::TAU
        } else {
            angle
        };
        Some(Radians::new(if angle >= core::f64::consts::TAU {
            0.0
        } else {
            angle
        }))
    }

    /// Converts to cartesian Direction.
    pub fn to_cartesian(&self) -> crate::cartesian::Direction<F>
    where
        F: ReferenceFrame,
    {
        use qtty::units::Radian;

        let polar_rad = self.polar.to::<Radian>();
        let azimuth_rad = self.azimuth.to::<Radian>();

        let x = azimuth_rad.cos() * polar_rad.cos();
        let y = azimuth_rad.sin() * polar_rad.cos();
        let z = polar_rad.sin();

        crate::cartesian::Direction::<F>::new(x, y, z)
    }

    /// Constructs a spherical direction from a cartesian Direction.
    ///
    /// The resulting angles are canonicalized:
    /// - `polar` in `[-90°, +90°]`
    /// - `azimuth` in `[0°, 360°)`
    pub fn from_cartesian(cart: &crate::cartesian::Direction<F>) -> Self
    where
        F: ReferenceFrame,
    {
        let (polar, azimuth) = super::xyz_to_polar_azimuth(cart.x(), cart.y(), cart.z());
        Self::new_unchecked(polar, azimuth)
    }
}

impl_quantity_fmt_triplet! {
    impl[F] for Direction<F>
    where { F: ReferenceFrame, },
    fmt_each: {},
    |this, f, FmtOne| {
        let (polar_name, azimuth_name, _) =
            F::spherical_names().unwrap_or(("\u{03b8}", "\u{03c6}", "r"));
        write!(f, "Frame: {}, {}: ", F::frame_name(), polar_name)?;
        FmtOne::fmt(&this.polar, f)?;
        write!(f, ", {}: ", azimuth_name)?;
        FmtOne::fmt(&this.azimuth, f)
    }
}

